'use strict';

const fs = require('fs');
const path = require('path');

const root = __dirname;
const partsDir = path.join(root, 'src', 'parts');
const outputDir = path.join(root, 'dist');
const outputFile = path.join(outputDir, 'index.js');

const parts = [
  '01-bootstrap-config.js',
  '02-monitoring-middleware-auth-plans.js',
  '03-request-context.js',
  '04-network-security.js',
  '05-content-sanitizers-embeds.js',
  '06-video-and-errors.js',
  '07-response-limits.js',
  '08-browser-manager.js',
  '09-scraper-engine.js',
  '10-validation-health.js',
  '11-api-routes.js',
  '12-shutdown-exports.js'
];

const missing = parts.filter(name => !fs.existsSync(path.join(partsDir, name)));
if (missing.length) {
  throw new Error(`Build üçün hissələr tapılmadı: ${missing.join(', ')}`);
}

fs.mkdirSync(outputDir, { recursive: true });
const banner = [
  '// AUTO-GENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.',
  '// Edit the ordered source parts in src/parts/ and run: npm run build',
  ''
].join('\n');
const source = banner + parts.map(name => {
  return `\n// ===== BEGIN ${name} =====\n` +
    fs.readFileSync(path.join(partsDir, name), 'utf8') +
    `\n// ===== END ${name} =====\n`;
}).join('\n');

fs.writeFileSync(outputFile, source, 'utf8');
console.log(`Build tamamlandı: ${path.relative(root, outputFile)} (${parts.length} hissə)`);
